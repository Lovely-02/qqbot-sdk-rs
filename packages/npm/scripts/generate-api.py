lines = ["// Generated by scripts/generate-api.py.", "import type { Message } from './index';", "export interface MediaTarget { kind: 'user' | 'group'; id: string }", "export interface BotApi {"]
for group, methods in groups.items():
    lines.append(f"  {group}: {{")
    for name, types in methods:
        lines.append(f"    {name}({', '.join(types)}): Promise<any>;")
    lines.append("  };")
lines += ["}", "export function createApi(call: (operation: string, args: unknown[]) => Promise<unknown>): BotApi {", "  const invoke = (operation: string, args: unknown[]) => call(operation, args.map(value => value === undefined ? null : value));", "  return {"]
for group, methods in groups.items():
    lines.append(f"    {group}: {{")
    for name, _ in methods:
        lines.append(f"      {name}: (...args: any[]) => invoke('{group}.{name}', args),")
    lines.append("    },")
lines += ["  };", "}"]
(root / "src" / "api.ts").write_text("\n".join(lines) + "\n", encoding="utf-8")

subprocess.run(["rustfmt", "--edition", "2024", str(root / "src" / "api.rs")], check=True)
